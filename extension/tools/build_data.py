"""Generate the extension's bundled data from the same references the crawler uses, so the extension
classifies hosts exactly like the training data:

  data/trackers.json   tracker domain -> [owner, categories]   (DuckDuckGo Tracker Data Set)
  data/entities.json   domain -> company, for third parties that are not trackers
  data/psl.json        Public Suffix List rules (ICANN section, tldextract's bundled snapshot)
  content/instrument.js  the crawler's instrumentation.js with its placeholders filled in

Run from the repository root after the crawler's reference files are refreshed:

    backend/.venv/bin/python extension/tools/build_data.py
"""

from __future__ import annotations

import json
from pathlib import Path

import tldextract

ROOT = Path(__file__).resolve().parents[2]
EXT = ROOT / "extension"
TDS = ROOT / "dataset_collection" / "reference" / "extension-tds.json"
INSTR = ROOT / "dataset_collection" / "ovael_crawler" / "instrumentation.js"

# The page reports counts by calling window[BINDING](snapshot); in the extension that function posts
# the snapshot to the content-script bridge in the same frame (see content/bridge.js).
BINDING_SHIM = """// Generated by extension/tools/build_data.py from dataset_collection/ovael_crawler/instrumentation.js.
// Do not edit; edit the crawler's file and rebuild, so live measurements match the training data.
(() => {
  try {
    Object.defineProperty(window, "__ovaelExtReport", {
      value: (snap) => { try { window.postMessage({ __ovaelExt: 1, snap }, "*"); } catch (e) {} },
      enumerable: false, configurable: false, writable: false,
    });
  } catch (e) {}
})();
"""


def main() -> None:
    tds = json.loads(TDS.read_text())
    trackers = {}
    for domain, t in tds["trackers"].items():
        owner = t.get("owner") or {}
        trackers[domain] = [owner.get("displayName") or owner.get("name") or "", t.get("categories") or []]
    names = {name: e.get("displayName") or name for name, e in tds["entities"].items()}
    entities = {d: names.get(name, name) for d, name in tds["domains"].items()}

    psl = tldextract.TLDExtract(suffix_list_urls=())._get_tld_extractor()
    rules = sorted(psl.public_tlds)

    data = EXT / "data"
    data.mkdir(exist_ok=True)
    (data / "trackers.json").write_text(json.dumps(trackers, separators=(",", ":")))
    (data / "entities.json").write_text(json.dumps(entities, separators=(",", ":")))
    (data / "psl.json").write_text(json.dumps(rules, separators=(",", ":")))
    (data / "meta.json").write_text(json.dumps({
        "tracker_reference": "DuckDuckGo Tracker Data Set (CC BY-NC-SA 4.0)",
        "tracker_built_with": tds.get("_builtWith"),
        "trackers": len(trackers), "entity_domains": len(entities), "psl_rules": len(rules),
    }, indent=1))

    src = INSTR.read_text()
    src = (src.replace('"__KEY__"', '"__ovael_ext_instrumentation__"')
              .replace('"__BINDING__"', '"__ovaelExtReport"')
              .replace("__MAX_EVENTS__", "0"))
    (EXT / "content" / "instrument.js").write_text(BINDING_SHIM + src)
    print(f"trackers={len(trackers)} entity_domains={len(entities)} psl_rules={len(rules)}")


if __name__ == "__main__":
    main()
